/** Translate a key, replacing {placeholders} with values. Falls back to English, then to the key. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let text = dictionary[lang][key] ?? dictionary.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  }
  return text;
}

/** Pick the Arabic text from the database when the site is in Arabic and an Arabic text exists. */
export function ltext(lang: Lang, english: string, arabic?: string | null): string {
  return lang === "ar" && arabic && arabic.trim() ? arabic : english;
}
